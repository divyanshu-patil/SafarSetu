import { networks } from "@repo/core";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: (string | number)[], t: string) => `array[${a.map((x) => (typeof x === "string" ? q(x) : x)).join(",")}]::${t}[]`;
const out: string[] = ["-- generated by `pnpm seed:sql` from @repo/core (SYNTHETIC demo data)"];
for (const n of Object.values(networks)) {
  for (const s of n.stops) out.push(`insert into stops values (${q(s.id + "@" + n.id)},${q(n.id)},${q(s.name)},${s.lat},${s.lon},${q(s.mode)}) on conflict do nothing;`);
  for (const r of n.routes) out.push(`insert into routes values (${q(r.id + "@" + n.id)},${q(n.id)},${q(r.mode)},${q(r.name)},${q(r.color)},${arr(r.stopIds, "text")},${arr(r.offsets, "int")},${arr(r.departures, "int")}) on conflict do nothing;`);
  for (const p of n.places) out.push(`insert into places values (${q(p.id + "@" + n.id)},${q(n.id)},${q(p.name)},${p.lat},${p.lon},${p.opens},${p.closes},${p.minDwell},${p.maxDwell},${q(p.category)}) on conflict do nothing;`);
}
console.log(out.join("\n"));
