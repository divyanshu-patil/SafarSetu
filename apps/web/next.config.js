const api = process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:4000";
const dev = process.env.NODE_ENV !== "production";

// GIGW 3.0 / CERT-In-minded baseline: no framing, no sniffing, tight sources. Inline scripts/styles are allowed because Next injects them.
const csp = [
  "default-src 'self'",
  `script-src 'self' 'unsafe-inline'${dev ? " 'unsafe-eval'" : ""}`,
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src 'self' https://fonts.gstatic.com",
  "img-src 'self' data: blob: https://tile.openstreetmap.org",
  `connect-src 'self' ${api}${dev ? " ws: wss:" : ""}`,
  "manifest-src 'self'",
  "frame-ancestors 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

/** @type {import('next').NextConfig} */
const nextConfig = {
  // @repo/core ships TypeScript source (shared with the Expo app)
  transpilePackages: ["@repo/core"],
  poweredByHeader: false,
  async headers() {
    return [
      {
        source: "/:path*",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          { key: "Permissions-Policy", value: "geolocation=(self), camera=(), microphone=()" },
        ],
      },
    ];
  },
};

export default nextConfig;
